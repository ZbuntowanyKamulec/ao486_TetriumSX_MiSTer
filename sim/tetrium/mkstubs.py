#!/usr/bin/env python3
"""Stub modules (all outputs 0, inouts undriven) from ANSI module headers: the SoC blocks the
simulation leaves out (sound / OPL3, GUS + its SDRAM, UARTs, MPU-401)."""
import re, sys
out = ["// generated by mkstubs.py: stubs of the SoC blocks left out of the simulation",
       "/* verilator lint_off UNUSEDSIGNAL */", "/* verilator lint_off DECLFILENAME */", "/* verilator lint_off UNDRIVEN */"]
for spec in sys.argv[1:]:
    path, name = spec.split(':')
    src = open(path, errors='replace').read()
    src = re.sub(r'//[^\n]*', '', src)
    m = re.search(r'\bmodule\s+%s\b\s*(#\s*\((?:[^()]|\([^()]*\))*\))?\s*\((.*?)\);' % name, src, re.S)
    hdr = m.group(2)
    ports = []
    for d in hdr.split(','):
        d = d.strip()
        if not d: continue
        mm = re.match(r'(input|output|inout)\s+(?:reg|wire|logic)?\s*(\[[^\]]*\])?\s*(\w+)$', d.replace('\n', ' ').strip())
        if mm: last = (mm.group(1), mm.group(2) or '')
        else:
            mm = re.match(r'(\w+)$', d); assert mm, d     # continuation: same direction / width
        nm = mm.group(3) if mm.lastindex and mm.lastindex >= 3 else mm.group(1)
        ports.append((last[0], last[1], nm))
    out.append("module %s (" % name)
    out.append(",\n".join("    %s %s %s" % (dr, w, n) for dr, w, n in ports))
    out.append(");")
    for dr, w, n in ports:
        if dr == 'output': out.append("  assign %s = '0;" % n)
    out.append("endmodule\n")
print("\n".join(out))

"""Generate bench/c/bigc/bigc.c: many functions (~20-25 KB of 8086 code) called
round-robin, to exercise the instruction cache like a large application."""
import random, sys
N = int(sys.argv[1]) if len(sys.argv) > 1 else 160
R = int(sys.argv[2]) if len(sys.argv) > 2 else 40
rnd = random.Random(8086)
out = ['/* generated by tools/genbigc.py: %d functions, %d rounds */' % (N, R),
       '#include <stdio.h>', 'static int arr[64];', 'static unsigned acc;', '']
for i in range(N):
    k = rnd.randrange(4)
    a, b, c = rnd.randrange(1, 60), rnd.randrange(1, 30), rnd.randrange(2, 9)
    body = []
    if k == 0:
        body += ['  int j, s = x;', '  for (j = 0; j < %d; j++) {' % c,
                 '    s += arr[(j * %d + x) & 63] ^ j;' % b,
                 '    if (s & %d) s -= %d; else s += j << 1;' % (1 << rnd.randrange(4), a), '  }',
                 '  arr[x & 63] = s;', '  return s;']
    elif k == 1:
        body += ['  int s = x * %d;' % b, '  switch ((x + %d) & 7) {' % a]
        for cs in range(8):
            body.append('  case %d: s += %d; break;' % (cs, rnd.randrange(100)))
        body += ['  }', '  if (s > %d) s = (s >> 1) + arr[%d];' % (a * 50, rnd.randrange(64)), '  return s;']
    elif k == 2:
        body += ['  int j, m = 0;', '  for (j = %d; j < %d; j += 3) {' % (rnd.randrange(8), 40 + c),
                 '    int v = arr[j & 63] + x;', '    if (v > m) m = v;',
                 '    else if (v < -%d) m -= %d;' % (a, b), '  }', '  arr[(x + %d) & 63] += m;' % a, '  return m ^ x;']
    else:
        body += ['  long t = (long)x * %d + %d;' % (a, b), '  int j;',
                 '  for (j = 0; j < %d; j++) t = (t >> 1) + arr[(j + x) & 63];' % c,
                 '  if (t & 1) t += %d;' % a, '  return (int)t;']
    out.append('int f%d(int x)\n{\n%s\n}\n' % (i, '\n'.join(body)))
out.append('int main(void)\n{\n  int r, x = 1;\n  for (r = 0; r < %d; r++) {' % R)
order = list(range(N))
for i in order:
    out.append('    x = f%d(x) + r; acc += x;' % i)
out.append('  }\n  printf("bigc acc=%x\\n", acc);\n  return 0;\n}')
open(sys.argv[3] if len(sys.argv) > 3 else 'bench/c/bigc/bigc.c', 'w').write('\n'.join(out) + '\n')
